/**
 * Record a triage edit (patient editing parsed values).
 * This triggers a re-run of Policy Research with the new context.
 */
export function recordTriageEdit(
  caseId: string,
  field: string,
  oldValue: string,
  newValue: string,
): TriageEdit {
  let history = versionStore.get(caseId);
  if (!history) {
    history = initVersionHistory(caseId);
  }

  const edit: TriageEdit = {
    field,
    oldValue,
    newValue,
    editedBy: 'human',
    editedAt: new Date().toISOString(),
  };

  history.triageEdits.push(edit);
  versionStore.set(caseId, history);

  // Persist to DB as a trace event
  db.decisionTraceEvent.create({
    data: {
      case_id: caseId,
      agent_name: 'human-edit',
      step: `triage_edit_${field}`,
      status: 'completed',
      details: JSON.stringify({
        detail: `Human edited triage field "${field}": "${oldValue}" → "${newValue}"`,
        field,
        oldValue,
        newValue,
      }),
    },
  }).catch(() => { /* best-effort */ });

  return edit;
}

/**
 * Get version history for a case.
 */
export function getVersionHistory(caseId: string): VersionHistory | null {
  return versionStore.get(caseId) || null;
}

/**
 * Get the current letter version for a case.
 */
export function getCurrentLetterVersion(caseId: string): LetterVersion | null {
  const history = versionStore.get(caseId);
  if (!history || history.letterVersions.length === 0) return null;
  return history.letterVersions[history.letterVersions.length - 1];
}

/**
 * Get a specific letter version.
 */
export function getLetterVersion(caseId: string, version: number): LetterVersion | null {
  const history = versionStore.get(caseId);
  if (!history) return null;
  return history.letterVersions.find(v => v.version === version) || null;
}

/**
 * Compare two letter versions (diff).
 */
export function diffVersions(
  caseId: string,
  versionA: number,
  versionB: number,
): { added: string[]; removed: string[]; changed: string[] } | null {
  const history = versionStore.get(caseId);
  if (!history) return null;

  const a = history.letterVersions.find(v => v.version === versionA);
  const b = history.letterVersions.find(v => v.version === versionB);
  if (!a || !b) return null;

  const linesA = a.appealLetter.split('\n');
  const linesB = b.appealLetter.split('\n');

  const added = linesB.filter(l => !linesA.includes(l));
  const removed = linesA.filter(l => !linesB.includes(l));
  const changed: string[] = [];

  // Find changed lines (same position, different content)
  const maxLen = Math.max(linesA.length, linesB.length);
  for (let i = 0; i < maxLen; i++) {
    if (i < linesA.length && i < linesB.length && linesA[i] !== linesB[i]) {
      changed.push(`Line ${i + 1}: "${linesA[i]}" → "${linesB[i]}"`);
    }
  }

  return { added, removed, changed };
}

// ─── Persistence Helper ───────────────────────────────────────────────────

async function persistVersionToDb(caseId: string, version: LetterVersion): Promise<void> {
  await db.decisionTraceEvent.create({
    data: {
      case_id: caseId,
      agent_name: version.editedBy === 'system' ? 'letter-drafting' : 'human-edit',
      step: `letter_version_${version.version}`,
      status: 'completed',
      details: JSON.stringify({
        detail: version.editReason,
        version: version.version,
        wordCount: version.wordCount,
        citationCount: version.inlineCitations.length,
        editedBy: version.editedBy,
        // Don't store the full letter in trace — just metadata
        letterPreview: version.appealLetter.slice(0, 200),
      }),
    },
  });
}
